-- =============================================================================
-- Field Tracker — 数据库迁移脚本
-- 从无到有创建全部 12 张表 + 索引 + 函数 + 触发器
-- 用法: psql -U postgres -d field_tracker -f migrate.sql
-- =============================================================================
-- 环境要求: PostgreSQL 16+
-- =============================================================================

BEGIN;

-- ============================================================
-- 错误处理：若任何语句失败则回滚全部
-- ============================================================
SET client_min_messages TO WARNING;

-- ============================================================
-- 扩展（按需启用）
-- ============================================================
-- CREATE EXTENSION IF NOT EXISTS postgis;      -- 地理空间查询
-- CREATE EXTENSION IF NOT EXISTS "uuid-ossp";  -- UUID 生成（gen_random_uuid 内置可用则非必需）

-- ============================================================
-- Schema
-- ============================================================
\i schema.sql

-- ============================================================
-- 验证：打印表结构摘要
-- ============================================================
DO $$
DECLARE
    tbl_count INT;
    idx_count INT;
BEGIN
    SELECT COUNT(*) INTO tbl_count
    FROM pg_tables
    WHERE schemaname = 'public';

    SELECT COUNT(*) INTO idx_count
    FROM pg_indexes
    WHERE schemaname = 'public';

    RAISE NOTICE '✅ 迁移完成：创建了 % 张表，% 个索引', tbl_count, idx_count;
END $$;

COMMIT;
